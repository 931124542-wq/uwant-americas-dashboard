const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');

const base = process.env.UWANT_TEST_BASE || 'http://127.0.0.1:8842/';
const mexico = '#country=MX&platform=ml&category=vacuum&page=market&shareMetric=units';
const out = path.resolve(process.argv[2]);

async function run() {
  const browser = await chromium.launch({
    executablePath:process.env.UWANT_CHROME_PATH || (process.platform==='darwin'?'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome':undefined)
  });
  try {
    await fs.mkdir(out,{recursive:true});
    const page = await browser.newPage({viewport:{width:1440,height:960},acceptDownloads:true});
    const errors = [];
    page.on('pageerror',error=>errors.push(error.message));
    await page.goto(base+mexico,{waitUntil:'domcontentloaded'});
    const card = page.locator('.ml-coverage-summary');
    await card.waitFor();
    assert.equal(await card.innerText(),'其他近30天快照');
    assert.equal(await card.locator('[data-ml-extra-snapshot]').isVisible(),false);
    assert.deepEqual((await page.locator('.market-kpi>strong').allTextContents()).slice(0,2),['117,092','8']);
    assert.equal(await page.locator('.market-kpi:visible').count(),3);
    await card.locator(':scope>summary').click();
    const supplement = card.locator('[data-ml-extra-snapshot]');
    assert.match(await supplement.innerText(),/499 台 · 1,091,300 MXN/);
    const pending = page.waitForEvent('download');
    await supplement.getByRole('button',{name:'导出该批'}).click();
    const file = await pending;
    await file.saveAs(out+'/nov12.csv');
    const csv = await fs.readFile(out+'/nov12.csv','utf8');
    assert.equal(csv.trim().split(/\r?\n/).length,118);
    assert(!csv.includes('2026-11-06'));
    await page.screenshot({path:out+'/mexico-overview.png'});

    const brandsChart=page.locator('.market-analysis-chart').filter({hasText:'品牌销量占比'});
    assert.doesNotMatch(await brandsChart.innerText(),/商品库.*来源品牌/);
    await page.locator('[data-overview-page="brands"]').click();
    const brands=page.locator('.market-brand-performance');
    await brands.waitFor();
    assert.match(await page.locator('.market-brand-sample').innerText(),/2026-11-06 有 3 个.*2026-11-12 有 13 个/);
    assert.equal(await brands.locator('tbody tr').count(),20);
    await page.locator('[data-market-brand-next]').click();
    assert.match(await page.locator('.market-brand-footer').innerText(),/第2 \/ 3页/);
    const brandSearch=page.locator('[data-market-brand-query]');
    await brandSearch.fill('rowenta');
    const rowenta=brands.getByRole('row').filter({hasText:'ROWENTA'});
    assert.equal(await rowenta.count(),1);
    assert.equal((await rowenta.locator('td').allTextContents()).slice(1,3).filter(x=>x.startsWith('—')).length,2);
    assert.match(await brands.locator('thead [data-ml-brand-archive]').innerText(),/2026-11-05/);
    assert.match(await brands.locator('thead').innerText(),/累计总销量/);
    const brandDownload=page.waitForEvent('download');
    await page.locator('#export').click();
    const brandCsv=await brandDownload;
    await brandCsv.saveAs(out+'/brands-rowenta.csv');
    const selectedBrand=await fs.readFile(out+'/brands-rowenta.csv','utf8');
    assert.match(selectedBrand,/"ROWENTA","2","units","MXN","2026-11-06","0","","","2026-11-12","0","",""/);
    assert.match(selectedBrand,/archiveDate.*lifetimeUnits/);
    await brandSearch.fill('Shark');
    const shark=brands.getByRole('row').filter({hasText:'SHARK'});
    assert.equal(await shark.count(),1);
    assert.match(await shark.innerText(),/16\s+—.*34/s);
    await shark.getByRole('button',{name:'查看商品'}).click();
    assert.equal(await page.locator('[data-ml-filter]').inputValue(),'SHARK');
    assert.equal(await page.locator('.ml-product').count(),16);
    await page.goto(base+mexico,{waitUntil:'domcontentloaded'});
    await card.waitFor();

    await card.locator(':scope>summary').click();
    await card.getByRole('button',{name:'查看商品库'}).click();
    const search = page.locator('[data-ml-query]');
    await search.fill('MLM49842392');
    const product = page.locator('.ml-product');
    assert.equal(await product.count(),1);
    assert.match(await product.innerText(),/Shark BU3120LAA.*公开商品页/s);
    assert.equal(await product.locator('a').getAttribute('href'),'https://www.mercadolibre.com.mx/shark-aspiradora-inalambrica-clean-empty-con-vaciado-automatico-hepa-9997-40-min-500x-menos-polvo-powerfins-autolimpiante-aspiradora-de-mano-desmontable-bu3120laa/p/MLM49842392');
    await search.fill('MLM2003963698');
    assert.equal(await product.count(),0,'Reviewed accessory cannot enter catalogue');
    const sources = await page.evaluate(()=>MERCADO_DATA.records.filter(r=>r.catalogueOnly).map(r=>[r.country,r.category,r.orders_last_30_days,r.revenue_last_30_days,r.counted]));
    assert.equal(sources.length,32);
    assert(sources.every(([country,category,units,revenue,counted])=>country==='MX'&&category==='vacuum'&&units===null&&revenue===null&&counted===false));

    await page.goto(base+mexico,{waitUntil:'domcontentloaded'});
    await card.waitFor();
    const dates=page.locator('#market-period');
    await dates.getByLabel('起始月份').fill('2026-09');
    await dates.getByLabel('结束月份').fill('2026-11');
    await dates.getByRole('button',{name:'应用',exact:true}).click();
    const monthly=page.locator('[data-ml-period-overview]');
    await monthly.waitFor();
    assert.match(await monthly.locator('.market-period-tag').innerText(),/2026-09 至 2026-11/);
    assert.equal(await monthly.locator('.market-kpi:visible').count(),2);
    assert.doesNotMatch(await monthly.innerText(),/有记录的商品链接|个去重商品组/);
    assert.deepEqual(await monthly.locator('[data-month-sample-units] strong').allTextContents(),['314 台','253 台']);
    assert.match(await monthly.locator('[data-period-month="2026-11"]').innerText(),/采集时未结月/);
    assert.equal(await monthly.locator('[data-period-month="2026-11"] [data-month-sample-units]').innerText(),'—');
    assert.deepEqual((await monthly.locator('.market-kpi>strong').allTextContents()).slice(0,2),['567','—']);
    assert.match(await monthly.innerText(),/有完整销量记录 2 \/ 3 月/);
    const productHistory=page.locator('.ml-product-history-fold');
    assert.equal(await productHistory.locator('[data-ml-history-product]').isVisible(),false);
    await productHistory.locator(':scope>summary').click();
    await productHistory.locator('[data-ml-history-product]').selectOption({index:1});
    assert.equal(await productHistory.locator('[data-ml-single-export]').isVisible(),true);
    assert.equal(await card.count(),0);
    const monthlyDownload=page.waitForEvent('download');
    await page.locator('#export').click();
    const csvFile=await monthlyDownload;
    assert.match(csvFile.suggestedFilename(),/_monthly_sample\.csv$/);
    await csvFile.saveAs(out+'/sep-nov-monthly-sample.csv');
    const historyCsv=await fs.readFile(out+'/sep-nov-monthly-sample.csv','utf8');
    assert.match(historyCsv,/"2026-09","314","9","19"/);
    assert.match(historyCsv,/"2026-10","253","6","23"/);
    assert.match(historyCsv,/"2026-11","","0","11"/);
    assert(historyCsv.includes('MLM18995515'));
    assert(!historyCsv.includes('"2026-08"'));
    await dates.getByLabel('结束月份').fill('2026-09');
    await dates.getByRole('button',{name:'应用',exact:true}).click();
    assert.equal(await monthly.locator('[data-market-kpi="units"] strong').innerText(),'314');
    await page.goBack();
    await page.waitForFunction(()=>state.endMonth==='2026-11');
    await page.reload({waitUntil:'domcontentloaded'});
    await monthly.waitFor();
    await page.locator('[data-market-time="overview"]').click();
    await card.waitFor();
    assert.deepEqual((await page.locator('.market-kpi>strong').allTextContents()).slice(0,2),['117,092','8']);
    await page.goBack();
    await monthly.waitFor();
    await page.setViewportSize({width:390,height:844});
    assert(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2));
    await page.screenshot({path:out+'/mexico-sept-nov.png'});

    await page.setViewportSize({width:390,height:844});
    await page.goto(base+mexico,{waitUntil:'domcontentloaded'});
    await card.waitFor();
    assert(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2));
    await card.scrollIntoViewIfNeeded();
    await page.screenshot({path:out+'/mexico-mobile.png'});
    await page.locator('[data-overview-page="brands"]').click();
    await brands.waitFor();
    assert(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2));
    assert.deepEqual(errors,[]);
    console.log('PASS Mexico coverage and all brands, separate batches, search, drilldown, export, accessory isolation and mobile.');
  } finally {
    await browser.close();
  }
}
run().catch(error=>{console.error(error);process.exitCode=1;});
